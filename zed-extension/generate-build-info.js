#!/usr/bin/env node

/**
 * Generate Build Information for Zed Extension
 * Creates a build_info.rs file with version, timestamp, and git commit info
 */

const fs = require('fs');
const path = require('path');

try {
  console.log('🏗️  Generating build information...\n');

  // Get versions from Cargo.toml files
  const cargoPath = path.join(__dirname, 'Cargo.toml');
  const extensionTomlPath = path.join(__dirname, 'extension.toml');
  const lspCargoPath = path.join(__dirname, '..', 'lsp-server', 'Cargo.toml');

  // Read extension version
  const cargoToml = fs.readFileSync(cargoPath, 'utf8');
  const versionMatch = cargoToml.match(/^version\s*=\s*"([^"]+)"/m);

  if (!versionMatch) {
    throw new Error('Could not parse version from Cargo.toml');
  }

  const version = versionMatch[1];

  // Read LSP version if available
  let lspVersion = 'unknown';
  if (fs.existsSync(lspCargoPath)) {
    const lspCargoToml = fs.readFileSync(lspCargoPath, 'utf8');
    const lspVersionMatch = lspCargoToml.match(/^version\s*=\s*"([^"]+)"/m);
    if (lspVersionMatch) {
      lspVersion = lspVersionMatch[1];
    }
  }

  // Generate build timestamp
  const buildTimestamp = new Date().toISOString();
  const buildNumber = Date.now();

  // Get git commit hash if available
  let gitCommit = 'unknown';
  let gitBranch = 'unknown';
  let gitDirty = false;

  try {
    const { execSync } = require('child_process');

    // Get commit hash
    gitCommit = execSync('git rev-parse --short HEAD', {
      encoding: 'utf8',
      stdio: ['pipe', 'pipe', 'ignore']
    }).trim();

    // Get branch name
    gitBranch = execSync('git rev-parse --abbrev-ref HEAD', {
      encoding: 'utf8',
      stdio: ['pipe', 'pipe', 'ignore']
    }).trim();

    // Check for uncommitted changes
    const status = execSync('git status --porcelain', {
      encoding: 'utf8',
      stdio: ['pipe', 'pipe', 'ignore']
    }).trim();
    gitDirty = status.length > 0;

  } catch (error) {
    console.log('   ℹ️  Git information not available');
  }

  // Create Rust build info source file
  const buildInfoContent = `// Auto-generated build information
// DO NOT EDIT THIS FILE MANUALLY
// Generated at: ${buildTimestamp}

/// Build information constants
pub mod build_info {
    /// Extension version
    pub const VERSION: &str = "${version}";

    /// LSP server version
    pub const LSP_VERSION: &str = "${lspVersion}";

    /// Build timestamp (ISO 8601)
    pub const BUILD_TIMESTAMP: &str = "${buildTimestamp}";

    /// Build number (Unix timestamp)
    pub const BUILD_NUMBER: u64 = ${buildNumber};

    /// Git commit hash
    pub const GIT_COMMIT: &str = "${gitCommit}";

    /// Git branch
    pub const GIT_BRANCH: &str = "${gitBranch}";

    /// Whether the working directory was dirty at build time
    pub const GIT_DIRTY: bool = ${gitDirty};

    /// Get a formatted build info string
    pub fn get_build_info() -> String {
        format!(
            "Log Scout Analyzer v{} (build {})",
            VERSION,
            BUILD_NUMBER
        )
    }

    /// Get detailed build information
    pub fn get_detailed_build_info() -> String {
        format!(
            "Extension: v{}\\nLSP Server: v{}\\nBuild: {}\\nBuild #: {}\\nGit: {}@{}{}",
            VERSION,
            LSP_VERSION,
            BUILD_TIMESTAMP,
            BUILD_NUMBER,
            GIT_BRANCH,
            GIT_COMMIT,
            if GIT_DIRTY { " (dirty)" } else { "" }
        )
    }
}

#[cfg(test)]
mod tests {
    use super::build_info::*;

    #[test]
    fn test_build_info() {
        assert!(!VERSION.is_empty());
        assert!(!BUILD_TIMESTAMP.is_empty());
        assert!(BUILD_NUMBER > 0);
    }

    #[test]
    fn test_get_build_info() {
        let info = get_build_info();
        assert!(info.contains("Log Scout Analyzer"));
        assert!(info.contains(VERSION));
    }

    #[test]
    fn test_get_detailed_build_info() {
        let info = get_detailed_build_info();
        assert!(info.contains("Extension:"));
        assert!(info.contains("LSP Server:"));
        assert!(info.contains("Build:"));
    }
}
`;

  // Write to src/build_info.rs
  const srcDir = path.join(__dirname, 'src');

  // Create src directory if it doesn't exist
  if (!fs.existsSync(srcDir)) {
    fs.mkdirSync(srcDir, { recursive: true });
    console.log('   ✓ Created src/ directory');
  }

  const outputPath = path.join(srcDir, 'build_info.rs');
  fs.writeFileSync(outputPath, buildInfoContent, 'utf8');

  console.log('✅ Build info generated successfully!');
  console.log(`   Version: ${version}`);
  console.log(`   LSP Version: ${lspVersion}`);
  console.log(`   Build: ${buildTimestamp}`);
  console.log(`   Build #: ${buildNumber}`);
  console.log(`   Git: ${gitBranch}@${gitCommit}${gitDirty ? ' (dirty)' : ''}`);
  console.log(`   Output: ${outputPath}`);
  console.log('');

  // Update lib.rs to include the build_info module if not already included
  const libPath = path.join(srcDir, 'lib.rs');
  if (fs.existsSync(libPath)) {
    let libContent = fs.readFileSync(libPath, 'utf8');

    // Check if build_info module is already declared
    if (!libContent.includes('mod build_info;') && !libContent.includes('pub mod build_info;')) {
      // Add at the beginning after any existing #! attributes
      const lines = libContent.split('\n');
      let insertIndex = 0;

      // Find the first line that's not a #! attribute or empty
      for (let i = 0; i < lines.length; i++) {
        const trimmed = lines[i].trim();
        if (!trimmed.startsWith('#!') && trimmed.length > 0) {
          insertIndex = i;
          break;
        }
      }

      lines.splice(insertIndex, 0, '', '// Build information (auto-generated)', 'mod build_info;', '');
      libContent = lines.join('\n');

      fs.writeFileSync(libPath, libContent, 'utf8');
      console.log('   ✓ Updated lib.rs to include build_info module');
    } else {
      console.log('   ℹ️  lib.rs already includes build_info module');
    }
  } else {
    console.log('   ⚠️  lib.rs not found - you may need to manually include the build_info module');
  }

} catch (error) {
  console.error('❌ Error generating build info:', error.message);
  process.exit(1);
}
