#!/usr/bin/env node
// Generate build information for Log Scout Analyzer VS Code extension
// This script creates a buildInfo.ts file with version and timestamp

const fs = require('fs');
const path = require('path');

// Get package.json version
const packageJson = require('./package.json');
const version = packageJson.version;

// Generate build timestamp
const buildTimestamp = new Date().toISOString();

// Generate a unique build number based on timestamp
const buildNumber = new Date().getTime();

// Get git commit hash if available
let gitCommit = 'unknown';
try {
    const { execSync } = require('child_process');
    gitCommit = execSync('git rev-parse --short HEAD', { encoding: 'utf8' }).trim();
} catch (error) {
    console.log('Note: Git commit hash not available');
}

// Create build info content
const buildInfoContent = `// Auto-generated build information
// DO NOT EDIT THIS FILE MANUALLY
// Generated at: ${buildTimestamp}

export const BUILD_INFO = {
    version: "${version}",
    buildTimestamp: "${buildTimestamp}",
    buildNumber: ${buildNumber},
    gitCommit: "${gitCommit}",
} as const;

export function getBuildInfo(): string {
    return \`Log Scout Analyzer v\${BUILD_INFO.version} (build \${BUILD_INFO.buildNumber})\`;
}

export function getDetailedBuildInfo(): string {
    return [
        \`Version: \${BUILD_INFO.version}\`,
        \`Build: \${BUILD_INFO.buildTimestamp}\`,
        \`Build #: \${BUILD_INFO.buildNumber}\`,
        \`Git: \${BUILD_INFO.gitCommit}\`,
    ].join('\\n');
}
`;

// Write to src/buildInfo.ts
const outputPath = path.join(__dirname, 'src', 'buildInfo.ts');
fs.writeFileSync(outputPath, buildInfoContent, 'utf8');

console.log('✅ Build info generated successfully!');
console.log(`   Version: ${version}`);
console.log(`   Build: ${buildTimestamp}`);
console.log(`   Build #: ${buildNumber}`);
console.log(`   Git: ${gitCommit}`);
console.log(`   Output: ${outputPath}`);
